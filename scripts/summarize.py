"""Collect every reports/*.json into one human-readable reports/RESULTS.md.
All numbers in the README / CV come from this file."""
import json
from pathlib import Path

R = Path(__file__).resolve().parents[1] / "reports"


def j(name):
    p = R / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def f(x, nd=3):
    return "—" if x is None else (f"{x:.{nd}f}" if isinstance(x, float) else str(x))


lines = ["# CallShield — measured results", "", "_Generated by `scripts/summarize.py` from `reports/*.json`._", ""]

s1 = j("stage1_cdr")
if s1:
    d = s1["data"]
    lines += ["## Stage 1 — call metadata (FraudZen SIM-box fraud)", "",
              f"{d['calls_total']:,} calls ({d['fraud_calls']:,} fraud) from {d['scenarios']} simulated scenarios. "
              f"Test = unseen scenarios + unseen legitimate subscribers; weighted test fraud rate {d['test_fraud_rate_weighted']:.1%}.", "",
              "| Model | PR-AUC | ROC-AUC | Precision | Recall | F1 | Recall @ 1% FPR |", "|---|---|---|---|---|---|---|"]
    for k, name in [("rule", "Operator rule (no data/SMS + call volume)"), ("logreg", "Logistic regression"),
                    ("lightgbm", "**LightGBM**"), ("ablation_no_hour_of_day", "LightGBM without hour-of-day")]:
        m = s1[k]
        lines.append(f"| {name} | {f(m.get('pr_auc'))} | {f(m.get('roc_auc'))} | {f(m['precision'])} | {f(m['recall'])} | {f(m['f1'])} | {f(m['recall_at_1pct_fpr'])} |")
    lines += ["", "LightGBM per fraud strategy (same test set, same threshold):", "",
              "| Strategy | Test fraud rate | PR-AUC | Precision | Recall |", "|---|---|---|---|---|"]
    for k, m in s1["lightgbm_per_strategy"].items():
        lines.append(f"| {k} | {m['positive_rate']:.1%} | {f(m.get('pr_auc'))} | {f(m['precision'])} | {f(m['recall'])} |")
    lines += ["", "Leave-one-strategy-out (train on two fraud strategies, test on the third):", "",
              "| Held-out strategy | PR-AUC | Recall @ 1% FPR |", "|---|---|---|"]
    for k, m in s1["leave_one_strategy_out"].items():
        lines.append(f"| {k} | {f(m.get('pr_auc'))} | {f(m['recall_at_1pct_fpr'])} |")
    top = list(s1["feature_importance_gain"].items())[:5]
    lines += ["", "Top features (gain share): " + ", ".join(f"{k} {v:.0%}" for k, v in top), ""]

b = j("stage2_baseline")
runs = {n: j(f"stage2_distilbert_{n}") for n in ("scamdialogue", "mix")}
if b or any(runs.values()):
    lines += ["## Stage 2 — call transcripts", "",
              "| Model | Trained on | Test: scam-dialogue | Test: single-agent | Real scam calls (YouTube) recall |", "|---|---|---|---|---|"]
    if b:
        for tr in ("scamdialogue", "singleagent", "mix"):
            r = b["results"]
            g = lambda te, k="f1": r.get(f"train={tr}|test={te}", {}).get(k)  # noqa: E731
            lines.append(f"| TF-IDF + LogReg | {tr} | F1 {f(g('scamdialogue'))} | F1 {f(g('singleagent'))} | {f(g('youtube', 'recall'))} |")
    for tr, r in runs.items():
        if r:
            g = lambda te, k="f1": r["results"].get(f"test={te}", {}).get(k)  # noqa: E731
            lines.append(f"| **DistilBERT** | {tr} | F1 {f(g('scamdialogue'))} | F1 {f(g('singleagent'))} | {f(g('youtube', 'recall'))} |")
            lines.append(f"|  | _train rows {r['train_rows']}, {r['train_minutes']} min on {r['hardware'].get('device')}_ | | | |")
    lines.append("")

o = j("stage2_onnx")
if o:
    sz, lat = o["sizes_mb"], o["latency_single_chunk"]
    acc = o["accuracy"]
    lines += ["## Stage 2 — ONNX export + INT8 dynamic quantisation", "",
              f"Single transcript chunk ({o['chunk_words']} words), {o['threads']} CPU threads.", "",
              "| Variant | Size (MB) | p50 latency (ms) | p95 latency (ms) | F1 single-agent | F1 scam-dialogue | Real-call recall |",
              "|---|---|---|---|---|---|---|"]
    for v, sk in [("pytorch_fp32", "pytorch_fp32"), ("onnx_fp32", "onnx_fp32"), ("onnx_int8", "onnx_int8")]:
        a = lambda te, k="f1": acc.get(f"{v}|test={te}", {}).get(k)  # noqa: E731
        lines.append(f"| {v} | {f(sz.get(sk), 1)} | {f(lat[v]['p50_ms'], 1)} | {f(lat[v]['p95_ms'], 1)} | "
                     f"{f(a('singleagent'))} | {f(a('scamdialogue'))} | {f(a('youtube', 'recall'))} |")
    lines.append("")

w = j("stage2_windows")
if w:
    lines += [f"## Stage 2 — live-call scoring with sliding windows ({w['window_words']} words, stride {w['stride_words']}), deployed INT8 model", "",
              "| Test set | Mode | Recall | Precision | F1 | False-positive rate (legit calls) |", "|---|---|---|---|---|---|"]
    for k, r in w.items():
        if not k.startswith("test="):
            continue
        for mode in ("first_window_only", "sliding_window_max"):
            m = r[mode]
            lines.append(f"| {k[5:]} | {mode} | {f(m['recall'])} | {f(m['precision'])} | {f(m['f1'])} | {f(m['false_positive_rate'])} |")
        lines.append(f"| {k[5:]} | median words until first warning (scams) | {f(r['median_words_until_warning_on_scams'], 0)} of {f(r['median_transcript_words'], 0)} | | | |")
    lines.append("")

for backend in ("memory", "redis"):
    a = j(f"api_bench_{backend}")
    if a:
        lines += [f"## API benchmark — HTTP end-to-end, history in {backend}, {a['workers']} workers", "",
                  "| Endpoint | p50 ms | p95 ms | p99 ms | Throughput (req/s) |", "|---|---|---|---|---|",
                  f"| /v1/calls/score | {a['stage1_latency']['p50_ms']} | {a['stage1_latency']['p95_ms']} | {a['stage1_latency']['p99_ms']} | {a['stage1_rps']} |"]
        if "stage2_latency" in a:
            lines.append(f"| /v1/transcript/score | {a['stage2_latency']['p50_ms']} | {a['stage2_latency']['p95_ms']} | {a['stage2_latency']['p99_ms']} | {a['stage2_rps']} |")
        lines += ["", f"Hardware: {a['hardware']}", ""]

(R / "RESULTS.md").write_text("\n".join(lines))
print("\n".join(lines))
